func semantic(ctx *ui.Context) theme.Semantic {
	active := ctx.Theme()
	return active.Semantic()
}

func providerColor(sem theme.Semantic, provider string) color.NRGBA {
	switch provider {
	case "claude":
		return color.NRGBA{R: 0xc0, G: 0x84, B: 0xfc, A: 0xff}
	case "codex":
		return color.NRGBA{R: 0x2d, G: 0xd4, B: 0xbf, A: 0xff}
	case "deepseek":
		return color.NRGBA{R: 0x60, G: 0xa5, B: 0xfa, A: 0xff}
	default:
		return sem.Tone(theme.TonePrimary).Fill
	}
}

func muted(sem theme.Semantic, value string, size float32) ui.Widget {
	return text.New(value).Size(size).Color(sem.MutedForeground)
}

func fixedCell(width int, child ui.Widget) ui.Widget {
	return layout.Box(child).Style(style.New().Width(unit.Dp(width))).Align(layout.AlignEnd)
}

func divider(sem theme.Semantic) ui.Widget {
	return layout.Divider().Color(sem.Separator)
}

func dot(value color.NRGBA, size int) ui.Widget {
	return ui.WidgetFunc(func(_ *ui.Context, gtx giolayout.Context) giolayout.Dimensions {
		diameter := gtx.Dp(unit.Dp(size))
		rect := image.Rect(0, 0, diameter, diameter)
		paint.FillShape(gtx.Ops, value, clip.UniformRRect(rect, diameter/2).Op(gtx.Ops))
		return giolayout.Dimensions{Size: image.Pt(diameter, diameter)}
	})
}

func shareBar(ratio float64, fill, track color.NRGBA) ui.Widget {
	return ui.WidgetFunc(func(_ *ui.Context, gtx giolayout.Context) giolayout.Dimensions {
		width, height := gtx.Dp(48), gtx.Dp(4)
		rect := image.Rect(0, 0, width, height)
		paint.FillShape(gtx.Ops, track, clip.UniformRRect(rect, height/2).Op(gtx.Ops))
		filled := int(math.Round(float64(width) * min(max(ratio, 0), 1)))
		if filled > 0 {
			filled = max(filled, height)
			paint.FillShape(gtx.Ops, fill,
				clip.UniformRRect(image.Rect(0, 0, filled, height), height/2).Op(gtx.Ops))
		}
		return giolayout.Dimensions{Size: image.Pt(width, height)}
	})
}

