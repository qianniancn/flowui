func costBody(ctx *ui.Context, m Model, r report, compact bool) ui.Widget {
	summary := costSummary(ctx, r)
	chart := dailyChart(ctx, m, r)
	if compact {
		return layout.Column(summary, chart).Gap(24)
	}
	return layout.Row(
		layout.Box(summary).Style(style.New().Width(240)),
		layout.Spacer(32, 0),
		layout.Expanded(chart),
	).AlignStart()
}

func costSummary(ctx *ui.Context, r report) ui.Widget {
	sem := semantic(ctx)
	subtitle := plural(r.sessions, "session")
	if r.unpriced > 0 {
		subtitle += " · " + percent(float64(r.unpriced)/float64(max(r.tokens.total(), 1))) + " of tokens unpriced"
	}
	children := []ui.Widget{
		text.New(money(r.cost)).Size(30).Weight(font.SemiBold).Color(sem.Foreground),
		text.New(subtitle).Size(12).Color(sem.MutedForeground),
	}
	for _, provider := range r.providers {
		children = append(children, providerRow(sem, provider, r.cost))
	}
	return layout.Column(children...).Gap(10)
}

func providerRow(sem theme.Semantic, provider providerUse, total float64) ui.Widget {
	share := 0.0
	if total > 0 {
		share = provider.cost / total
	}
	return layout.Column(
		layout.Row(
			layout.Expanded(layout.Row(
				dot(providerColor(sem, provider.provider), 8),
				text.New(providerName(provider.provider)).Size(14).Color(sem.Foreground),
				text.New(plural(provider.sessions, "session")).Size(12).Color(sem.MutedForeground),
			).Gap(6).AlignMiddle()),
			text.New(money(provider.cost)).Size(14).Weight(font.Medium).Color(sem.Foreground),
		).AlignMiddle(),
		text.New(percent(share)+" of cost · "+compact(provider.tokens.total())+" tokens").
			Size(12).Color(sem.MutedForeground),
	).Gap(2)
}

func dailyChart(ctx *ui.Context, m Model, r report) ui.Widget {
	sem := semantic(ctx)
	series := make([]linechart.Series, 0, len(r.providers))
	for i, provider := range r.providers {
		line := linechart.Values(
			provider.provider,
			providerName(provider.provider),
			provider.daily,
		).
			Color(providerColor(sem, provider.provider)).
			Width(2).
			ShowPoints(false).
			Smooth(true)
		if i == 0 {
			line = line.Area(true)
		}
		series = append(series, line)
	}
	categories := make([]string, len(r.days))
	for i, day := range r.days {
		categories[i] = day.Format("Jan 2")
	}
	chart := linechart.New("usage-daily", series).
		Categories(categories).
		Height(180).
		Legend(false).
		Tooltip(false).
		Grid(true).
		YTicks(4).
		IncludeZero(true).
		FormatY(axisMoney).
		Animation(false).
		DataVersion(uint64(m.Window))
	return layout.Column(
		text.New("Daily cost").Size(13).Weight(font.Medium).Color(sem.Foreground),
		chart,
	).Gap(12)
}

