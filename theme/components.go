// applyDerivedComponents overwrites the board's colour slots that are palette
// roles rather than design decisions: a menu background *is* the overlay
// surface, a timeline primary *is* the accent. The board leaves those slots at
// zero and states them once, here.
//
// UseSemantic calls it, so a theme cannot install a palette and leave the board
// stale. Every construction path goes through UseSemantic — New, NewDark, and
// the two style packages, each of which calls it again after New.
//
// Geometry is untouched: that half is the framework's own baseline, not a Seed
// derivation follows the component visual protocol.
func applyDerivedComponents(t *Theme) {
	p := t.Palette
	c := &t.Components

	c.Workbench.SidebarBackground = p.SurfaceSecondary
	c.Workbench.SidebarForeground = p.SurfaceSecondaryForeground
	c.Workbench.SidebarHoverBackground = p.SurfaceHover
	c.Workbench.SidebarActiveBackground = p.AccentSoft
	c.Workbench.SidebarActiveForeground = p.AccentSoftForeground
	c.Workbench.SidebarBorder = p.Border
	c.Workbench.EditorBackground = p.Background
	c.Workbench.EditorForeground = p.Foreground
	c.Workbench.EditorTabBackground = p.SurfaceSecondary
	c.Workbench.EditorTabHoverBackground = p.SurfaceHover
	c.Workbench.EditorTabActiveBackground = p.Surface
	c.Workbench.EditorTabActiveForeground = p.SurfaceForeground
	c.Workbench.BottomPanelBackground = p.SurfaceSecondary
	c.Workbench.BottomPanelForeground = p.SurfaceSecondaryForeground
	c.Workbench.BottomPanelBorder = p.Border
	c.Workbench.StatusBarBackground = p.SurfaceTertiary
	c.Workbench.StatusBarForeground = p.SurfaceTertiaryForeground
	c.Workbench.DividerColor = p.Border
	c.Workbench.DividerHoverColor = p.Accent

	c.Timeline.TailColor = p.Border
	c.Timeline.DotBackground = p.Surface
	c.Timeline.TitleColor = p.Foreground
	c.Timeline.ContentColor = p.SurfaceForeground
	c.Timeline.MutedColor = p.MutedForeground
	c.Timeline.PrimaryColor = p.Accent
	c.Timeline.ErrorColor = p.Danger
	c.Timeline.SuccessColor = p.Success
	c.Timeline.DisabledColor = p.MutedForeground

	c.Menu.BackgroundColor = p.Overlay
	c.Menu.ForegroundColor = p.OverlayForeground
	c.Menu.MutedColor = p.MutedForeground
	c.Menu.IndicatorColor = p.Accent
	c.Menu.DangerColor = p.Danger
	c.Menu.FocusColor = p.Focus

	c.Dropdown.FocusColor = p.Focus

	c.TitleBar.ControlPressed = p.SurfacePressed
	c.Table.StripeBackground = p.SurfaceSecondary
	c.NodeGraph = nodeGraphThemeFor(p)
}
