func limitsCard(ctx *ui.Context, limits []planLimit, now time.Time) ui.Widget {
	sem := semantic(ctx)
	blocks := make([]ui.Widget, 0, len(limits))
	for _, limit := range limits {
		blocks = append(blocks, limitBlock(sem, limit, now))
	}
	return card.New(
		text.New("Limits").Size(14).Weight(font.Medium).Color(sem.Foreground),
		text.New("How much of each plan limit the agents used, as they last reported it. Bars turn yellow at 80% and red at 95%.").
			Size(12).Color(sem.MutedForeground),
		layout.Column(blocks...).Gap(20),
	).StyleWithMetrics(style.New().FillWidth(), 20, 16)
}

func limitBlock(sem theme.Semantic, limit planLimit, now time.Time) ui.Widget {
	children := []ui.Widget{
		layout.Row(
			dot(providerColor(sem, limit.provider), 8),
			text.New(limitTitle(limit)).Size(14).Weight(font.Medium).Color(sem.Foreground),
			text.New("As of "+ago(now.Sub(limit.seen))).Size(12).Color(sem.MutedForeground),
		).Gap(6).AlignMiddle(),
	}
	for _, window := range limit.windows {
		children = append(children, limitWindowWidget(sem, limit, window, now))
	}
	return layout.Column(children...).Gap(14)
}

func limitWindowWidget(sem theme.Semantic, limit planLimit, window limitWindow, now time.Time) ui.Widget {
	used := window.used
	if !window.resets.IsZero() && !now.Before(window.resets) {
		used = 0
	}
	fill := limitColor(sem, limit.provider, used)
	meter := progress.Meter(
		"limit-"+limit.provider+"-"+strconv.FormatInt(window.minutes, 10),
		used,
	).
		Label(windowName(window.minutes)+" window").
		ShowValue().
		Range(0, 100).
		Size(progress.MeterSmall).
		Fill(fill).
		Style(style.Style{}.
			Part(style.PartTrack, style.Style{}.
				Height(6).
				Radius(3).
				Background(style.Solid(sem.SurfaceRaised))))
	return layout.Column(
		meter,
		text.New(windowNote(window, limit.seen, now)).
			Size(12).Color(sem.MutedForeground),
	).Gap(6)
}

func limitColor(sem theme.Semantic, provider string, used float64) color.NRGBA {
	switch {
	case used >= 95:
		return sem.Tone(theme.ToneDanger).Fill
	case used >= 80:
		return sem.Tone(theme.ToneWarning).Fill
	default:
		return providerColor(sem, provider)
	}
}

