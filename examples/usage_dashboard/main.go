type category struct {
	key  string
	name string
	desc string
}

var categories = []category{
	{"usage", "Usage", "Your plan limits and what your coding agents cost."},
	{"appearance", "Appearance", "Theme, fonts and spacing."},
	{"agents", "Agents", "Claude Code, Codex, and DeepSeek sessions on this machine."},
	{"about", "About", "Version, demo data, and the navigation shell."},
}

type bannerMessage struct {
	key         string
	title       string
	description string
	status      alert.Status
	priority    int
}

type notification struct {
	title       string
	description string
	status      alert.Status
	at          time.Time
	read        bool
}

type Model struct {
	Window            int // 7, 30, or 90 days
	ByDay             bool
	Category          string
	Banners           []bannerMessage
	History           []notification
	ShowNotifications bool
	Reports           map[int]report
	Limits            []planLimit
}

type Msg any

type windowChanged int
type breakdownChanged bool
type categoryChanged string
type bannerDismissed struct{}
type notificationsToggled struct{}
type notificationsRead struct{}
type notificationsCleared struct{}
type feedbackReset struct{}

func Update(m *Model, msg Msg) ui.Cmd[Msg] {
	switch msg := msg.(type) {
	case windowChanged:
		m.Window = int(msg)
	case breakdownChanged:
		m.ByDay = bool(msg)
	case categoryChanged:
		m.Category = string(msg)
		m.ShowNotifications = false
	case bannerDismissed:
		banner, ok := currentBanner(m.Banners)
		if !ok {
			break
		}
		m.Banners = removeBanner(m.Banners, banner.key)
		m.History = append([]notification{{
			title:       banner.title,
			description: banner.description,
			status:      banner.status,
			at:          time.Now(),
		}}, m.History...)
	case notificationsToggled:
		m.ShowNotifications = !m.ShowNotifications
	case notificationsRead:
		for i := range m.History {
			m.History[i].read = true
		}
	case notificationsCleared:
		m.History = nil
	case feedbackReset:
		m.Banners = demoBanners()
		m.History = nil
		m.ShowNotifications = false
	}
	return nil
}

func demoBanners() []bannerMessage {
	return []bannerMessage{
		{
			key:         "read-only-demo",
			title:       "Read-only demo",
			description: "This example never reads Claude Code, Codex, or DeepSeek session files.",
			status:      alert.Warning,
			priority:    30,
		},
		{
			key:         "demo-data",
			title:       "Demo data",
			description: "Limits, costs, and tokens are generated by the example at startup.",
			status:      alert.Accent,
			priority:    20,
		},
	}
}

func currentBanner(banners []bannerMessage) (bannerMessage, bool) {
	if len(banners) == 0 {
		return bannerMessage{}, false
	}
	top := banners[0]
	for _, banner := range banners[1:] {
		if banner.priority > top.priority {
			top = banner
		}
	}
	return top, true
}

func removeBanner(banners []bannerMessage, key string) []bannerMessage {
	for i, banner := range banners {
		if banner.key == key {
			return append(banners[:i], banners[i+1:]...)
		}
	}
	return banners
}

func unreadCount(history []notification) int {
	count := 0
	for _, item := range history {
		if !item.read {
			count++
		}
	}
	return count
}

func View(_ *ui.Context, m Model, send ui.Send[Msg]) ui.Widget {
	return ui.WidgetFunc(func(ctx *ui.Context, gtx giolayout.Context) giolayout.Dimensions {
		width := gtx.Constraints.Max.X
		if width < gtx.Dp(960) {
			return compactShell(ctx, m, send, width < gtx.Dp(820)).Layout(ctx, gtx)
		}
		sidebarWidth := gtx.Dp(232)
		return wideShell(ctx, m, send, width-sidebarWidth < gtx.Dp(820)).Layout(ctx, gtx)
	})
}

func wideShell(ctx *ui.Context, m Model, send ui.Send[Msg], compact bool) ui.Widget {
	sem := semantic(ctx)
	// Overlay keeps the content width stable when switching between a long
	// page (Usage) and a short one; a gutter scrollbar would make it jump.
	content := layout.Scroll(
		layout.Box(settingsContent(ctx, m, send, compact)).
			Style(style.New().FillWidth().MaxWidth(1080).Padding(24)),
	).Overlay().Key("settings-content-" + m.Category).Vertical()
	return layout.Row(
		layout.Box(settingsNav(ctx, m, send)).
			Style(style.New().FillHeight().Background(style.Solid(sem.SurfaceSecondary))),
		layout.Divider().Vertical().Color(sem.Separator),
		layout.Expanded(content),
	)
}

func compactShell(ctx *ui.Context, m Model, send ui.Send[Msg], compact bool) ui.Widget {
	sem := semantic(ctx)
	items := make([]selectfield.SelectItem, 0, len(categories))
	for _, category := range categories {
		items = append(items, selectfield.SelectItem{Key: category.key, Label: category.name})
	}
	selector := selectfield.New(items).
		Key("settings-category").
		SelectedKey(m.Category).
		OnChange(func(key string) { send(categoryChanged(key)) })
	header := layout.Row(
		text.New("Settings").Size(16).Weight(font.SemiBold).Color(sem.Foreground),
		layout.Expanded(layout.Spacer(0, 0)),
		layout.Box(selector).Style(style.New().Width(240)),
	).AlignMiddle()
	body := layout.Column(
		header,
		layout.Divider().Color(sem.Separator),
		settingsContent(ctx, m, send, compact),
	).Gap(16)
	return layout.Box(
		layout.Scroll(
			layout.Box(body).Style(style.New().FillWidth().Padding(20)),
		).Overlay().Key("settings-content-" + m.Category).Vertical(),
	).Style(style.New().FillWidth().FillHeight())
}

func settingsNav(ctx *ui.Context, m Model, send ui.Send[Msg]) ui.Widget {
	sem := semantic(ctx)
	header := text.New("Settings").Size(16).Weight(font.SemiBold).Color(sem.Foreground)
	items := make([]sidebar.Item, 0, len(categories))
	for _, category := range categories {
		items = append(items, sidebar.Item{Key: category.key, Label: category.name})
	}
	unread := unreadCount(m.History)
	label := "Notifications"
	if unread > 0 {
		label = fmt.Sprintf("Notifications · %d", unread)
	}
	variant := button.Ghost
	if m.ShowNotifications {
		variant = button.Secondary
	}
	footer := layout.Column(
		button.New(label).Key("notifications-toggle").
			Variant(variant).
			Size(button.Small).
			FullWidth().
			OnClick(func() { send(notificationsToggled{}) }),
		text.New("FlowUI · usage demo").Size(11).Color(sem.MutedForeground),
	).Gap(6)
	return sidebar.New("settings-nav", m.Category, items).
		Header(header).
		Footer(footer).
		Width(232).
		Padding(12).
		ContentGap(16).
		ItemHeight(36).
		ItemGap(2).
		OnChange(func(key string) { send(categoryChanged(key)) })
}

func categoryByKey(key string) category {
	for _, category := range categories {
		if category.key == key {
			return category
		}
	}
	return categories[0]
}

func settingsContent(ctx *ui.Context, m Model, send ui.Send[Msg], compact bool) ui.Widget {
	content := usageContent(ctx, m, send, compact)
	if m.ShowNotifications {
		content = notificationsContent(ctx, m, send)
	} else if m.Category != "usage" {
		content = settingsPlaceholder(ctx, m, send)
	}
	banner, ok := currentBanner(m.Banners)
	if !ok {
		return content
	}
	alertBanner := alert.New(banner.title, banner.description).
		Key(banner.key).
		Status(banner.status).
		Closable(true).
		OnClose(func() { send(bannerDismissed{}) })
	return layout.Column(alertBanner, content).Gap(20)
}

func notificationsContent(ctx *ui.Context, m Model, send ui.Send[Msg]) ui.Widget {
	sem := semantic(ctx)
	now := time.Now()
	unread := unreadCount(m.History)
	actions := layout.Row(
		button.New("Back").Variant(button.Ghost).Size(button.Small).
			OnClick(func() { send(notificationsToggled{}) }),
		layout.Expanded(layout.Spacer(0, 0)),
		button.New("Mark all read").Variant(button.Ghost).Size(button.Small).
			Disabled(unread == 0).
			OnClick(func() { send(notificationsRead{}) }),
		button.New("Clear").Variant(button.Ghost).Size(button.Small).
			Disabled(len(m.History) == 0).
			OnClick(func() { send(notificationsCleared{}) }),
		button.New("Reset demo").Variant(button.Secondary).Size(button.Small).
			OnClick(func() { send(feedbackReset{}) }),
	).Gap(8).AlignMiddle()

	var list ui.Widget = card.New(
		text.New("Nothing here yet").Size(14).Weight(font.Medium).Color(sem.Foreground),
		text.New("Dismiss a banner and it will appear in this history.").Size(12).Color(sem.MutedForeground),
	).StyleWithMetrics(style.New().FillWidth(), 16, 12)
	if len(m.History) > 0 {
		rows := make([]ui.Widget, 0, len(m.History))
		for _, item := range m.History {
			rows = append(rows, notificationCard(sem, item, now))
		}
		list = layout.Column(rows...).Gap(10)
	}
	return layout.Column(
		layout.Column(
			text.New("Notifications").Size(28).Weight(font.SemiBold).
				Color(sem.Foreground).LineHeightScale(1.2),
			text.New("Dismissed banners and operation feedback from this demo.").
				Size(13).Color(sem.MutedForeground),
		).Gap(4),
		actions,
		list,
	).Gap(20)
}

func notificationCard(sem theme.Semantic, item notification, now time.Time) ui.Widget {
	titleColor := sem.Foreground
	if item.read {
		titleColor = sem.MutedForeground
	}
	return card.New(
		layout.Row(
			dot(alertStatusColor(sem, item.status), 8),
			layout.Expanded(text.New(item.title).Size(14).Weight(font.Medium).Color(titleColor)),
			text.New(ago(now.Sub(item.at))).Size(11).Color(sem.MutedForeground),
		).Gap(8).AlignMiddle(),
		text.New(item.description).Size(12).Color(sem.MutedForeground),
	).StyleWithMetrics(style.New().FillWidth(), 16, 12)
}

func alertStatusColor(sem theme.Semantic, status alert.Status) color.NRGBA {
	switch status {
	case alert.Success:
		return sem.Tone(theme.ToneSuccess).Fill
	case alert.Warning:
		return sem.Tone(theme.ToneWarning).Fill
	case alert.Danger:
		return sem.Tone(theme.ToneDanger).Fill
	case alert.Accent:
		return sem.Tone(theme.TonePrimary).Fill
	default:
		return sem.MutedForeground
	}
}

