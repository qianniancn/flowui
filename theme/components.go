// FrameworkComponents is the framework's neutral component geometry board: the radius,
// padding, height and colour every component group starts from, before a style
// package overrides the groups it disagrees with.
//
// It is a constant, not a derivation. Geometry is a design decision, not a
// function of a seed: the button radius here is 24 while the input radius is 12,
// for one radius input, and the recipes read these fields directly rather than
// falling back to a default of their own. So this board is the only carrier of
// the framework's geometry — clearing a value here makes it zero, it does not
// fall back to anything.
//
// A slot that is a palette role is left at zero here on purpose — a menu
// background *is* the overlay surface, a timeline primary *is* the accent — and
// stated once, by the derived layer (applyDerivedComponents). Writing one here
// would be a second source of truth that a
// theme is free to contradict. The colours that do appear below are the ones no
// palette role covers: the window controls' traffic lights, the chart series and
// heatmap scales.
//
// These values define FlowUI's default geometry. External Providers inherit
// this baseline and override only the component groups their design changes.
