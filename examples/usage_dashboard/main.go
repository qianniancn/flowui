type breakdownLine struct {
	provider string
	name     string
	cost     string
	share    float64 // -1 when unpriced
	tokens   int64
	priced   bool
	dim      bool
}

func breakdownTable(ctx *ui.Context, r report, byDay, compact bool) ui.Widget {
	sem := semantic(ctx)
	var lines []breakdownLine
	if byDay {
		lines = make([]breakdownLine, 0, len(r.days))
		for i := len(r.days) - 1; i >= 0; i-- {
			day := r.daily[i]
			share := 0.0
			if r.cost > 0 {
				share = day.cost / r.cost
			}
			lines = append(lines, breakdownLine{
				name:   r.days[i].Format("Mon, Jan 2"),
				cost:   money(day.cost),
				share:  share,
				tokens: day.tokens.total(),
				priced: true,
				dim:    day.tokens.total() == 0,
			})
		}
	} else {
		lines = make([]breakdownLine, 0, len(r.models))
		for _, model := range r.models {
			line := breakdownLine{
				provider: model.provider,
				name:     model.model,
				cost:     money(model.cost),
				share:    model.cost / max(r.cost, 1e-9),
				tokens:   model.tokens.total(),
				priced:   model.priced,
			}
			if !model.priced {
				line.cost = "Unpriced"
				line.share = -1
			}
			lines = append(lines, line)
		}
	}

	top := 0.0
	for _, line := range lines {
		top = max(top, line.share)
	}

	costWidth, shareWidth, tokenWidth := 96, 132, 72
	if compact {
		costWidth, shareWidth, tokenWidth = 76, 104, 60
	}
	nameLabel := "Model"
	if byDay {
		nameLabel = "Day"
	}

	header := layout.Row(
		layout.Expanded(muted(sem, nameLabel, 12)),
		fixedCell(costWidth, muted(sem, "Cost", 12)),
		fixedCell(shareWidth, muted(sem, "Share", 12)),
		fixedCell(tokenWidth, muted(sem, "Tokens", 12)),
	).Gap(12).AlignMiddle()

	rows := []ui.Widget{layout.Box(header).Style(style.New().FillWidth().PaddingY(6))}
	rows = append(rows, divider(sem))
	for i, line := range lines {
		rows = append(rows, tableRow(ctx, sem, line, top, costWidth, shareWidth, tokenWidth))
		if i < len(lines)-1 {
			rows = append(rows, divider(sem))
		}
	}
	return layout.Column(rows...)
}

func tableRow(ctx *ui.Context, sem theme.Semantic, line breakdownLine, top float64, costWidth, shareWidth, tokenWidth int) ui.Widget {
	fg := sem.Foreground
	if line.dim {
		fg = sem.MutedForeground
	}
	var name ui.Widget = text.New(line.name).Size(13).Color(fg).MaxLines(1).Truncator("…")
	if line.provider != "" {
		name = layout.Row(
			dot(providerColor(sem, line.provider), 8),
			name,
		).Gap(8).AlignMiddle()
	}
	var share ui.Widget = text.New("—").Size(13).Color(sem.MutedForeground)
	if line.priced && line.share >= 0 {
		ratio := 0.0
		if top > 0 {
			ratio = line.share / top
		}
		share = layout.Row(
			shareBar(ratio, providerColor(sem, line.provider), sem.SurfaceRaised),
			text.New(percent(line.share)).Size(12).Color(fg),
		).Gap(8).AlignMiddle()
	}
	costColor := fg
	if !line.priced {
		costColor = sem.MutedForeground
	}
	row := layout.Row(
		layout.Expanded(name),
		fixedCell(costWidth, text.New(line.cost).Size(13).Color(costColor)),
		fixedCell(shareWidth, share),
		fixedCell(tokenWidth, text.New(compact(line.tokens)).Size(13).Color(fg)),
	).Gap(12).AlignMiddle()
	return layout.Box(row).Style(style.New().FillWidth().PaddingY(8))
}

